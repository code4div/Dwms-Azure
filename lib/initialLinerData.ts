/**
 * Generates wall layout for any specified chute in the plant
 */
export function getChuteWallsForChute(targetChuteId: string): ChuteWall[] {
  const chuteConfig = PLANT_CHUTES.find((c) => c.id === targetChuteId) || PLANT_CHUTES[0];

  return chuteWallsData.map((wall) => ({
    ...wall,
    rows: wall.rows.map((row, rowIndex) => ({
      liners: row.liners.map((baseLiner, linerIndex) => {
        let wear = baseLiner.wear;
        let status = baseLiner.status;
        let material = baseLiner.material;
        let zone = baseLiner.zone;

        // Customise per chute to match real plant wear profile and reference screenshots
        if (targetChuteId === "CH-001") {
          // Standard reference CH-001: 2B is 93.4%, 1B is 81.2%
          if (baseLiner.id === "2B" && rowIndex === 0) {
            wear = 93.4;
            status = "imminent";
            material = "Chromium Carbide Overlay 8+8";
            zone = "Back Plate";
          } else if (baseLiner.id === "1B") {
            wear = 81.2;
            status = "critical";
            material = "Ceramic Composite 92% Al2O3";
            zone = "Impact";
          }
        } else if (targetChuteId === "CH-002") {
          // CH-002: Peak wear 88.1% on 4B (Critical)
          if (baseLiner.id === "4B") {
            wear = 88.1;
            status = "critical";
            material = "Bi-metallic White Iron Tile";
            zone = "Discharge";
          } else if (baseLiner.id === "4G") {
            wear = 0.0;
            status = "offline";
          } else {
            wear = Math.min(76, Math.max(12, Number((baseLiner.wear * 0.92).toFixed(1))));
            status = wear >= 50 ? "action" : wear >= 26 ? "monitor" : "healthy";
          }
        } else if (targetChuteId === "CH-003") {
          // CH-003: Peak wear 91.6% on 2J (Imminent), 80.5% on 1A (Critical)
          if (baseLiner.id === "2J" || (baseLiner.id === "2B" && rowIndex === 1)) {
            wear = 91.6;
            status = "imminent";
            material = "Ceramic Composite 92% Al2O3";
            zone = "Rear Wall";
          } else if (baseLiner.id === "1A") {
            wear = 80.5;
            status = "critical";
            material = "Ceramic Composite 92% Al2O3";
            zone = "Impact";
          } else {
            wear = Math.min(79, Math.max(11, Number((baseLiner.wear * 1.05).toFixed(1))));
            status = wear >= 50 ? "action" : wear >= 26 ? "monitor" : "healthy";
          }
        } else if (targetChuteId === "CH-004") {
          // CH-004: Max wear 71.8% on 3A (Action Required)
          if (baseLiner.id === "3A") {
            wear = 71.8;
            status = "action";
            material = "AR400 Wear Steel";
            zone = "Side Wall";
          } else {
            wear = Math.min(68, Math.max(9, Number((baseLiner.wear * 0.82).toFixed(1))));
            status = wear >= 50 ? "action" : wear >= 26 ? "monitor" : "healthy";
          }
        } else if (targetChuteId === "CH-005") {
          // CH-005: Peak wear 80.1% on 3F (Critical)
          if (baseLiner.id === "3F") {
            wear = 80.1;
            status = "critical";
            material = "Polyurethane Composite Plate";
            zone = "Side Wall";
          } else {
            wear = Math.min(77, Math.max(10, Number((baseLiner.wear * 0.96).toFixed(1))));
            status = wear >= 50 ? "action" : wear >= 26 ? "monitor" : "healthy";
          }
        }

        const origThickness = baseLiner.origThickness || 30;
        const thickness = Number((origThickness * ((100 - wear) / 100)).toFixed(1));
        const rulDays = Math.max(15, Math.round(baseLiner.rulDays * ((100 - wear) / (100 - (baseLiner.wear || 50)))));

        return {
          ...baseLiner,
          fullCode: baseLiner.fullCode ? baseLiner.fullCode.replace('CH-001', targetChuteId) : `${targetChuteId}·${baseLiner.id}`,
          wear,
          thickness,
          status,
          rulDays,
          material,
          zone,
          chuteId: targetChuteId,
          junctionId: chuteConfig.junction,
        };
      }),
    })),
  }));
}

/**
 * Returns all 200 liners across the entire plant (5 chutes × 40 liners)
 */
export function getAllPlantLiners(): LinerPlate[] {
  const allLiners: LinerPlate[] = [];

  PLANT_CHUTES.forEach((chute) => {
    const walls = getChuteWallsForChute(chute.id);
    walls.forEach((wall) => {
      wall.rows.forEach((row) => {
        row.liners.forEach((liner) => {
          allLiners.push(liner);
        });
      });
    });
  });

  return allLiners;
}
